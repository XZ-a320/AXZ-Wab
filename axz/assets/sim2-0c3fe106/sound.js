/* ==========================================================================
   AXZ sim — sound, synthesised rather than sampled.

   Why not a sound pack. A jet's noise is a continuous function of N1, airspeed
   and how much air is going through the fan; a looped sample is one operating
   point stretched over all of them, and the seam is audible the moment you
   move the thrust lever. Everything here is generated by Web Audio and driven
   by the same state the flight model already computes, so spooling up actually
   sounds like spooling up and the airflow rises with indicated airspeed.

   It also keeps the page honest. Downloadable packs come with licences to
   track and megabytes to ship on a page whose whole engine is 180 KB, and this
   is a few hundred lines of oscillators.

   Everything is behind an explicit toggle and starts muted-until-gesture,
   because a page that makes noise on load is a page people close.
   ========================================================================== */

import { clamp } from './math.js'

/** Steady band-limited noise, generated once and looped. */
function noiseBuffer(ctx, seconds = 2) {
  const n = Math.floor(ctx.sampleRate * seconds)
  const buf = ctx.createBuffer(1, n, ctx.sampleRate)
  const d = buf.getChannelData(0)
  // Pink-ish: white through a cheap one-pole, which sits far better under a
  // jet than flat white noise does.
  let last = 0
  for (let i = 0; i < n; i++) {
    const w = Math.random() * 2 - 1
    last = (last + 0.02 * w) / 1.02
    d[i] = last * 3.5
  }
  return buf
}

/* --- Engine voices --------------------------------------------------------
   Four families, because the roster now holds four genuinely different kinds
   of engine and the difference is audible from a mile away. What separates
   them is not a pitch offset, it is which layer carries the sound:

   - a high-bypass fan is mostly the FAN: a bright blade-passing whine over a
     soft exhaust, and the bigger the fan the lower the whine sits, which is
     why a 2.8 m GEnx hums where a 1.3 m business-jet fan sings.
   - a reheated turbojet is mostly EXHAUST: no bypass air to shield it, so it
     is raw broadband roar with a hard edge, and lighting the reheat adds a
     low ripping rumble underneath.
   - a low-bypass military fan sits between them, with a hard compressor whine
     and the same burner rumble on top.
   - a piston is not a turbine at all. It is a firing pulse train in the low
     hundreds of hertz plus the propeller's own blade slap, and rendering it
     through the turbofan voice was the reason the Cessna sounded like a
     narrowbody with the volume down.

   `bpf` is the blade-passing band at idle and at full power, in hertz.       */
const VOICES = {
  turbofan: {
    bpf: [620, 2370], whine: 0.075, whine2: 0.028,
    exhaust: [320, 4120], exhaustG: [0.22, 0.94], rumble: [0.35, 1.20],
    hiss: 0.0, burner: 0, tone: 'sine',
  },
  // A smaller fan turns faster: the same blade count, a higher passing tone.
  'turbofan-small': {
    bpf: [900, 3450], whine: 0.085, whine2: 0.034,
    exhaust: [380, 4600], exhaustG: [0.18, 0.82], rumble: [0.24, 0.86],
    hiss: 0.05, burner: 0, tone: 'sine',
  },
  // Low bypass. Harder compressor tone, more exhaust, and a burner.
  'turbofan-ab': {
    bpf: [420, 1560], whine: 0.11, whine2: 0.055,
    exhaust: [300, 6200], exhaustG: [0.30, 1.15], rumble: [0.30, 1.05],
    hiss: 0.10, burner: 1, tone: 'sawtooth',
  },
  // No bypass at all. The exhaust IS the aeroplane.
  'turbojet-reheat': {
    bpf: [360, 1180], whine: 0.09, whine2: 0.048,
    exhaust: [280, 7000], exhaustG: [0.34, 1.28], rumble: [0.40, 1.30],
    hiss: 0.14, burner: 1, tone: 'sawtooth',
  },
  piston: {
    // 2,400 rpm on a four-cylinder is two firing events a revolution: 80 Hz,
    // and the two-blade propeller passes at the same rate.
    bpf: [42, 96], whine: 0.0, whine2: 0.0,
    exhaust: [220, 900], exhaustG: [0.16, 0.44], rumble: [0.20, 0.52],
    hiss: 0.0, burner: 0, tone: 'sawtooth', firing: true,
  },
}

/* --- Warning packs --------------------------------------------------------
   The alerts are the one part of this that is NOT synthesised, and the reason
   is simple: a Boeing low-speed alert is a recorded human voice saying
   AIRSPEED LOW, and a synthesised approximation of a specific recorded voice
   is not an approximation of anything. So these five are audio files, cut to
   one repeat cycle each and looped.

   Which pack an aeroplane gets is a real property of the aeroplane. A Boeing
   flight deck says AIRSPEED LOW; an Airbus gives you the stall warning and the
   cricket. The Gulfstream is on the same Honeywell terrain box as the Boeings
   and says the same words. A Cessna's stall warning is a pneumatic reed horn
   in the wing leading edge and a fighter has its own voice, so neither gets
   an airliner's alerts: they keep the synthesised tone.                     */
/* --- Radio-altimeter callouts ---------------------------------------------
   The voice that counts you down to the runway. These are the automatic
   height calls an airliner makes on every approach, and they are the reason a
   landing has a rhythm: you stop reading the altimeter somewhere around five
   hundred and fly the last of it on what you are being told.

   Fired on DESCENT through each height and armed again only after climbing
   back above it, so a float in the flare does not stutter "twenty" at you four
   times. RETARD rides on the ten-foot call, which is where an Airbus says it.
   The list is descending because that is the order they happen in.          */
const CALLOUTS = [
  [2500, 'callout-2500'], [1000, 'callout-1000'], [500, 'callout-500'],
  [400, 'callout-400'], [300, 'callout-300'], [200, 'callout-200'],
  [100, 'callout-100'], [70, 'callout-70'], [60, 'callout-60'],
  [50, 'callout-50'], [40, 'callout-40'], [30, 'callout-30'],
  [20, 'callout-20'], [10, 'callout-10'], [5, 'callout-5'],
]

const WARN_PACKS = {
  boeing: { stall: 'warn-boeing-airspeed', pullup: 'warn-boeing-pullup', master: 'warn-boeing-master' },
  airbus: { stall: 'warn-airbus-stall', pullup: 'warn-boeing-pullup', master: 'warn-airbus-master' },
}

export class Sound {
  constructor(audioBase) {
    this.ready = false
    this.enabled = false
    this.ctx = null
    this.master = null
    this.voice = VOICES.turbofan
    this.audioBase = audioBase || ''
    this.clips = {}          // name -> decoded AudioBuffer
    this.pack = null         // the current type's alert set, or null for synth
    this.playing = {}        // name -> live looping source
  }

  /**
   * Fetch and decode the alert clips. Called once, from the same press that
   * starts the simulator, so a reader who never presses it downloads none of
   * this — the same contract the engine itself is under.
   */
  async loadClips() {
    if (!this.ctx || !this.audioBase || this.clipsLoading) return
    this.clipsLoading = true
    const names = new Set()
    for (const p of Object.values(WARN_PACKS)) for (const n of Object.values(p)) names.add(n)
    for (const [, n] of CALLOUTS) names.add(n)
    names.add('callout-above'); names.add('callout-gear')
    await Promise.all([...names].map(async name => {
      try {
        const res = await fetch(this.audioBase + name + '.m4a')
        if (!res.ok) return
        this.clips[name] = await this.ctx.decodeAudioData(await res.arrayBuffer())
      } catch (e) { /* a missing alert falls back to the synthesised tone */ }
    }))
  }

  /** Play a clip once. Used by the height callouts, which never loop. */
  playClip(name, gain = 1.0) {
    if (!this.ready || !this.enabled) return false
    const buf = this.clips[name]
    if (!buf) return false
    const src = this.ctx.createBufferSource()
    src.buffer = buf
    const g = this.ctx.createGain()
    g.gain.value = gain
    src.connect(g); g.connect(this.master)
    src.start()
    return true
  }

  /**
   * The automatic height calls, fired on descent through each one.
   *
   * Armed again only after climbing back above the height plus a margin, so a
   * float in the flare cannot stutter the same call at you four times — which
   * is the whole difficulty with doing this off a threshold rather than off an
   * edge.
   */
  callouts(ac) {
    if (!this.pack) return               // only the types that have the voice
    if (!this.armed) this.armed = {}
    const ra = (ac.radioAlt != null ? ac.radioAlt : ac.agl) * 3.280839895
    if (ac.onGround || ac.crashed || !(ra > 0)) return
    for (const [ft, clip] of CALLOUTS) {
      if (ra > ft * 1.12 + 3) { this.armed[ft] = true; continue }
      if (ra <= ft && this.armed[ft]) {
        this.armed[ft] = false
        /* One call per frame, and no wall-clock cooldown. The arming
           hysteresis above already stops a float in the flare from repeating
           a call, and a rate limit measured against the audio clock silently
           swallowed the whole descent below a thousand feet: coming down at
           three thousand a minute you pass fifty, forty, thirty and twenty
           inside a second, and a real one calls all four. */
        this.playClip(clip, 0.95)
        break
      }
    }
  }

  /** Start a looping alert, or do nothing if it is already running. */
  loopClip(name, gain = 0.9) {
    if (!this.ready || !this.enabled || this.playing[name]) return false
    const buf = this.clips[name]
    if (!buf) return false
    const src = this.ctx.createBufferSource()
    src.buffer = buf
    src.loop = true
    const g = this.ctx.createGain()
    g.gain.value = gain
    src.connect(g); g.connect(this.master)
    src.start()
    this.playing[name] = { src, g }
    return true
  }

  /** Stop a looping alert, with a short release so it does not click off. */
  stopClip(name) {
    const p = this.playing[name]
    if (!p) return
    delete this.playing[name]
    const t = this.ctx.currentTime
    try {
      p.g.gain.setTargetAtTime(0, t, 0.03)
      p.src.stop(t + 0.2)
    } catch (e) { /* already stopped */ }
  }

  stopAllClips() { for (const n of Object.keys(this.playing)) this.stopClip(n) }

  /**
   * Point the engine voice at a type. Safe before `init`, because the aircraft
   * is chosen while the simulator is still being constructed and the audio
   * context does not exist until somebody presses Sound.
   */
  setEngine(spec) {
    this.voice = VOICES[spec && spec.engine] || (spec && spec.prop ? VOICES.piston : VOICES.turbofan)
    this.engines = (spec && spec.engines) || 2
    // Swapping type mid-alert would leave the old aeroplane's voice shouting.
    this.stopAllClips()
    this.pack = WARN_PACKS[spec && spec.warnPack] || null
    if (this.ready) this.applyVoice()
  }

  /** Re-point the oscillators that only change when the type does. */
  applyVoice() {
    const v = this.voice
    if (!this.eng) return
    this.eng.whine.type = v.tone
    this.eng.whine2.type = v.tone
    /* Four engines are not one engine four times as loud. What four sound like
       is one engine plus a beat, because they never run at exactly the same
       speed — so the second whine is detuned by a few hertz on a quad and left
       alone on a twin. */
    this.eng.detune = this.engines >= 4 ? 5.5 : this.engines === 1 ? 0 : 2.2
  }

  /**
   * Must be called from a user gesture. Browsers will not start an AudioContext
   * any other way, and this one is started from the same press that downloads
   * the engine.
   */
  init() {
    if (this.ctx) return true
    const AC = window.AudioContext || window.webkitAudioContext
    if (!AC) return false
    try {
      const ctx = new AC()
      this.ctx = ctx
      this.master = ctx.createGain()
      this.master.gain.value = 0
      // A limiter on the bus: an explosion plus a stall horn plus full thrust
      // can otherwise clip, and clipping sounds like a broken page.
      const comp = ctx.createDynamicsCompressor()
      comp.threshold.value = -10
      comp.knee.value = 18
      comp.ratio.value = 8
      comp.attack.value = 0.004
      comp.release.value = 0.22
      this.master.connect(comp)
      comp.connect(ctx.destination)

      this.noise = noiseBuffer(ctx, 3)
      this.buildEngine()
      this.buildAir()
      this.buildWarnings()
      this.ready = true
      this.applyVoice()
      return true
    } catch (e) {
      this.ready = false
      return false
    }
  }

  /* --- Engine -------------------------------------------------------------
     Three layers, because a turbofan is three noises: the fan whine (a tone
     an octave or so up, tracking N1), the core rumble (a low tone), and the
     jet itself (broadband noise through a lowpass that opens with thrust). */
  buildEngine() {
    /* Rebuilt. The first version led with a sawtooth at 78-246 Hz, which is
       a bass buzz: it read as a synthesiser drone rather than an engine,
       because a turbofan's dominant tone is NOT down there. What a jet
       actually is, in order of energy:

         - broadband exhaust noise, with the spectrum opening upward as thrust
           comes up. This is most of the sound and it is noise, not a tone.
         - a high blade-passing whine, up around one to three kilohertz, which
           is the part your ear identifies as "jet".
         - a low body rumble under both.

       So: no sawtooth anywhere, noise carries the weight, and the only tonal
       elements are the whine and its second harmonic, kept quiet. */
    const ctx = this.ctx
    this.eng = {}

    const g = ctx.createGain(); g.gain.value = 0
    g.connect(this.master)
    this.eng.out = g

    // --- Broadband exhaust. Two filters: a lowpass that opens with thrust,
    // and a highpass that keeps the bottom end from turning to mud.
    const jet = ctx.createBufferSource()
    jet.buffer = this.noise; jet.loop = true
    const jetHP = ctx.createBiquadFilter()
    jetHP.type = 'highpass'; jetHP.frequency.value = 160
    const jetLP = ctx.createBiquadFilter()
    jetLP.type = 'lowpass'; jetLP.frequency.value = 400; jetLP.Q.value = 0.6
    const jetG = ctx.createGain(); jetG.gain.value = 0.5
    jet.connect(jetHP); jetHP.connect(jetLP); jetLP.connect(jetG); jetG.connect(g)
    jet.start()
    this.eng.jetLP = jetLP; this.eng.jetG = jetG

    // --- Body rumble: the same noise, taken low.
    const rum = ctx.createBufferSource()
    rum.buffer = this.noise; rum.loop = true
    const rumLP = ctx.createBiquadFilter()
    rumLP.type = 'lowpass'; rumLP.frequency.value = 90; rumLP.Q.value = 1.4
    const rumG = ctx.createGain(); rumG.gain.value = 0.9
    rum.connect(rumLP); rumLP.connect(rumG); rumG.connect(g)
    rum.start()
    this.eng.rumG = rumG

    // --- Blade-passing whine. A sine, not a sawtooth: a saw at this frequency
    // brings a stack of harmonics that turn into a reedy buzz. The second
    // harmonic is added separately and much quieter, which is the amount of
    // edge a fan actually has.
    const whine = ctx.createOscillator()
    whine.type = 'sine'; whine.frequency.value = 700
    const whineG = ctx.createGain(); whineG.gain.value = 0
    whine.connect(whineG); whineG.connect(g)
    whine.start()
    const whine2 = ctx.createOscillator()
    whine2.type = 'sine'; whine2.frequency.value = 1400
    const whine2G = ctx.createGain(); whine2G.gain.value = 0
    whine2.connect(whine2G); whine2G.connect(g)
    whine2.start()
    this.eng.whine = whine; this.eng.whineG = whineG
    this.eng.whine2 = whine2; this.eng.whine2G = whine2G

    /* --- Reheat. A lit burner is not "the engine, louder". It is a separate
       noise source with its own character: a wide band with the bottom left in
       and a resonant peak that opens as the nozzle does, which is the ripping
       sound rather than the roar. Silent on every type without one, which is
       eight of the eleven. */
    const ab = ctx.createBufferSource()
    ab.buffer = this.noise; ab.loop = true
    const abBP = ctx.createBiquadFilter()
    abBP.type = 'bandpass'; abBP.frequency.value = 220; abBP.Q.value = 0.45
    const abLow = ctx.createBiquadFilter()
    abLow.type = 'lowshelf'; abLow.frequency.value = 140; abLow.gain.value = 9
    const abG = ctx.createGain(); abG.gain.value = 0
    ab.connect(abBP); abBP.connect(abLow); abLow.connect(abG); abG.connect(g)
    ab.start()
    this.eng.abBP = abBP; this.eng.abG = abG

    /* --- Breathing. A slow, shallow wobble on the exhaust level. Steady noise
       at a fixed gain sounds synthetic within about two seconds; real engine
       noise never sits perfectly still. */
    const lfo = ctx.createOscillator()
    lfo.type = 'sine'; lfo.frequency.value = 0.27
    const lfoG = ctx.createGain(); lfoG.gain.value = 0.055
    lfo.connect(lfoG); lfoG.connect(jetG.gain)
    lfo.start()
    this.eng.detune = 2.2
  }

  /** Airflow over the hull, plus the rumble of wheels on concrete. */
  buildAir() {
    const ctx = this.ctx
    const g = ctx.createGain(); g.gain.value = 0
    g.connect(this.master)

    const src = ctx.createBufferSource()
    src.buffer = this.noise; src.loop = true
    const f = ctx.createBiquadFilter()
    f.type = 'bandpass'; f.frequency.value = 700; f.Q.value = 0.5
    src.connect(f); f.connect(g)
    src.start()
    this.air = { out: g, filter: f }

    const rg = ctx.createGain(); rg.gain.value = 0
    rg.connect(this.master)
    const rsrc = ctx.createBufferSource()
    rsrc.buffer = this.noise; rsrc.loop = true
    const rf = ctx.createBiquadFilter()
    rf.type = 'lowpass'; rf.frequency.value = 160; rf.Q.value = 1.1
    rsrc.connect(rf); rf.connect(rg)
    rsrc.start()
    this.roll = { out: rg, filter: rf }
  }

  /** Stall warning and overspeed clacker, both gated by the flight model. */
  buildWarnings() {
    const ctx = this.ctx
    const g = ctx.createGain(); g.gain.value = 0
    g.connect(this.master)
    const o = ctx.createOscillator()
    o.type = 'square'; o.frequency.value = 780
    const og = ctx.createGain(); og.gain.value = 0.08
    o.connect(og); og.connect(g); o.start()
    this.warn = { out: g }
    this.warnPhase = 0
    this.clackPhase = 0
  }

  setEnabled(on) {
    this.enabled = on
    if (!this.ready) return
    if (!on) this.stopAllClips()
    if (on && this.ctx.state === 'suspended') this.ctx.resume()
    const t = this.ctx.currentTime
    this.master.gain.cancelScheduledValues(t)
    this.master.gain.setTargetAtTime(on ? 0.85 : 0, t, 0.08)
  }

  /** One-shot helpers ---------------------------------------------------- */
  blip(freq, dur, type = 'sine', gain = 0.2) {
    if (!this.ready || !this.enabled) return
    const ctx = this.ctx, t = ctx.currentTime
    const o = ctx.createOscillator(), g = ctx.createGain()
    o.type = type; o.frequency.setValueAtTime(freq, t)
    g.gain.setValueAtTime(0, t)
    g.gain.linearRampToValueAtTime(gain, t + 0.008)
    g.gain.exponentialRampToValueAtTime(0.0001, t + dur)
    o.connect(g); g.connect(this.master)
    o.start(t); o.stop(t + dur + 0.02)
  }

  /** Wheels meeting concrete. Scaled by how hard the arrival was. */
  touchdown(fpm) {
    if (!this.ready || !this.enabled) return
    const ctx = this.ctx, t = ctx.currentTime
    const hard = clamp(fpm / 700, 0.12, 1.6)
    const src = ctx.createBufferSource()
    src.buffer = this.noise
    const f = ctx.createBiquadFilter()
    f.type = 'lowpass'
    f.frequency.setValueAtTime(120 + hard * 900, t)
    f.frequency.exponentialRampToValueAtTime(90, t + 0.35)
    const g = ctx.createGain()
    g.gain.setValueAtTime(0, t)
    g.gain.linearRampToValueAtTime(0.5 * hard, t + 0.012)
    g.gain.exponentialRampToValueAtTime(0.0001, t + 0.45)
    src.connect(f); f.connect(g); g.connect(this.master)
    src.start(t, Math.random() * 2, 0.6)
    // The thud under it.
    const o = ctx.createOscillator(), og = ctx.createGain()
    o.type = 'sine'
    o.frequency.setValueAtTime(70, t)
    o.frequency.exponentialRampToValueAtTime(34, t + 0.28)
    og.gain.setValueAtTime(0, t)
    og.gain.linearRampToValueAtTime(0.42 * hard, t + 0.01)
    og.gain.exponentialRampToValueAtTime(0.0001, t + 0.4)
    o.connect(og); og.connect(this.master)
    o.start(t); o.stop(t + 0.45)
  }

  /* --- Sonic boom ---------------------------------------------------------
     Not a bang. An N-wave: the bow shock arrives, the pressure drops below
     ambient behind it, and the tail shock brings it back — which the ear hears
     as two cracks about a tenth of a second apart with a hollow between them.
     Every recording of one is a double, and a single thump is the thing that
     makes a simulator sound wrong.

     From inside you never hear your own. The shock cone trails behind the
     aeroplane and the cockpit is ahead of it, so this plays quietly on the
     outside cameras and is nearly silent in the flight deck — which is itself
     the most surprising true thing about going supersonic. */
  sonicBoom(inside) {
    if (!this.ready || !this.enabled) return
    const ctx = this.ctx, t = ctx.currentTime
    const level = inside ? 0.10 : 1
    const crack = (at, gain) => {
      const src = ctx.createBufferSource()
      src.buffer = this.noise
      const hp = ctx.createBiquadFilter()
      hp.type = 'highpass'; hp.frequency.value = 90
      const lp = ctx.createBiquadFilter()
      lp.type = 'lowpass'
      lp.frequency.setValueAtTime(7000, at)
      lp.frequency.exponentialRampToValueAtTime(220, at + 0.22)
      const g = ctx.createGain()
      g.gain.setValueAtTime(0, at)
      g.gain.linearRampToValueAtTime(gain * level, at + 0.004)
      g.gain.exponentialRampToValueAtTime(0.0001, at + 0.30)
      src.connect(hp); hp.connect(lp); lp.connect(g); g.connect(this.master)
      src.start(at, Math.random() * 2, 0.4)
      // The pressure step under each crack, which is what you feel.
      const o = ctx.createOscillator(), og = ctx.createGain()
      o.type = 'sine'
      o.frequency.setValueAtTime(62, at)
      o.frequency.exponentialRampToValueAtTime(21, at + 0.26)
      og.gain.setValueAtTime(0, at)
      og.gain.linearRampToValueAtTime(0.7 * gain * level, at + 0.008)
      og.gain.exponentialRampToValueAtTime(0.0001, at + 0.34)
      o.connect(og); og.connect(this.master)
      o.start(at); o.stop(at + 0.36)
    }
    crack(t, 0.85)
    crack(t + 0.11, 0.62)
  }

  /** The single chime that says something on the aeroplane has just gone. */
  alertOnce() {
    if (!this.ready || !this.enabled) return
    if (this.pack && this.playClip(this.pack.master, 0.85)) return
    // No voice pack on this type: two descending tones, which is what a
    // caution chime is on everything that does not talk.
    this.blip(880, 0.20, 'sine', 0.22)
    setTimeout(() => this.blip(660, 0.32, 'sine', 0.22), 190)
  }

  /** Servo whine for gear and flaps. */
  servo(up) {
    if (!this.ready || !this.enabled) return
    const ctx = this.ctx, t = ctx.currentTime
    const o = ctx.createOscillator(), g = ctx.createGain()
    o.type = 'sawtooth'
    o.frequency.setValueAtTime(up ? 220 : 300, t)
    o.frequency.linearRampToValueAtTime(up ? 300 : 210, t + 1.1)
    const f = ctx.createBiquadFilter()
    f.type = 'bandpass'; f.frequency.value = 900; f.Q.value = 5
    g.gain.setValueAtTime(0, t)
    g.gain.linearRampToValueAtTime(0.09, t + 0.12)
    g.gain.setValueAtTime(0.09, t + 0.9)
    g.gain.exponentialRampToValueAtTime(0.0001, t + 1.25)
    o.connect(f); f.connect(g); g.connect(this.master)
    o.start(t); o.stop(t + 1.3)
  }

  /* --- Explosion ----------------------------------------------------------
     A crack, a body of broadband noise sweeping down, and a sub-bass thump
     that arrives with it. Then a tail of crackle. */
  explosion(energy = 1) {
    if (!this.ready || !this.enabled) return
    const ctx = this.ctx, t = ctx.currentTime
    const E = clamp(energy, 0.4, 1.8)

    const src = ctx.createBufferSource()
    src.buffer = this.noise
    const f = ctx.createBiquadFilter()
    f.type = 'lowpass'
    f.frequency.setValueAtTime(5200, t)
    f.frequency.exponentialRampToValueAtTime(150, t + 1.6)
    const g = ctx.createGain()
    g.gain.setValueAtTime(0, t)
    g.gain.linearRampToValueAtTime(0.95 * E, t + 0.012)
    g.gain.exponentialRampToValueAtTime(0.0001, t + 2.2)
    src.connect(f); f.connect(g); g.connect(this.master)
    src.start(t, Math.random(), 2.4)

    const sub = ctx.createOscillator(), sg = ctx.createGain()
    sub.type = 'sine'
    sub.frequency.setValueAtTime(88, t)
    sub.frequency.exponentialRampToValueAtTime(24, t + 1.1)
    sg.gain.setValueAtTime(0, t)
    sg.gain.linearRampToValueAtTime(0.85 * E, t + 0.02)
    sg.gain.exponentialRampToValueAtTime(0.0001, t + 1.5)
    sub.connect(sg); sg.connect(this.master)
    sub.start(t); sub.stop(t + 1.6)

    // Crackle: a scatter of short bursts over the next couple of seconds.
    for (let i = 0; i < 14; i++) {
      const dt = 0.25 + Math.random() * 2.0
      const cs = ctx.createBufferSource()
      cs.buffer = this.noise
      const cf = ctx.createBiquadFilter()
      cf.type = 'bandpass'; cf.frequency.value = 700 + Math.random() * 2600; cf.Q.value = 2
      const cg = ctx.createGain()
      cg.gain.setValueAtTime(0, t + dt)
      cg.gain.linearRampToValueAtTime(0.10 * E, t + dt + 0.006)
      cg.gain.exponentialRampToValueAtTime(0.0001, t + dt + 0.16)
      cs.connect(cf); cf.connect(cg); cg.connect(this.master)
      cs.start(t + dt, Math.random() * 2, 0.2)
    }
  }

  /* --- Per-frame ----------------------------------------------------------
     Everything continuous is a setTargetAtTime toward the value the physics
     just produced. Instant assignment would zipper. */
  update(ac, dt, cameraInside) {
    if (!this.ready || !this.enabled) return
    const ctx = this.ctx, t = ctx.currentTime
    const tc = 0.09

    // Engine. N1 is the spooled state, so the sound lags the lever exactly as
    // the thrust does, and the voice is whichever family this type flies.
    const v = this.voice
    const n1 = clamp(ac.thrustLag, 0, 1)
    const ab = ac.abFrac || 0
    const inside = cameraInside ? 1 : 0
    /* Past Mach 1 the aeroplane is ahead of its own shock cone, so from the
       flight deck the engines go quiet and only the boundary layer is left.
       Going through the barrier the cabin gets QUIETER, which is what every
       Concorde passenger remembers and no simulator ever models. */
    const supers = clamp(((ac.mach || 0) - 0.98) / 0.08, 0, 1)
    // Exhaust opens upward with thrust; that sweep IS the sound of spooling.
    this.eng.jetLP.frequency.setTargetAtTime(v.exhaust[0] + n1 * (v.exhaust[1] - v.exhaust[0]), t, tc)
    this.eng.jetG.gain.setTargetAtTime(v.exhaustG[0] + n1 * (v.exhaustG[1] - v.exhaustG[0]) + v.hiss * n1, t, tc)
    this.eng.rumG.gain.setTargetAtTime(v.rumble[0] + n1 * (v.rumble[1] - v.rumble[0]), t, tc)
    /* Blade passing, or on a piston the firing rate. Both are "how fast is the
       thing turning", and both are the layer an ear identifies the machine by,
       which is why they share a slot rather than being two code paths. */
    const bpf = v.bpf[0] + n1 * (v.bpf[1] - v.bpf[0])
    this.eng.whine.frequency.setTargetAtTime(bpf, t, tc)
    this.eng.whine2.frequency.setTargetAtTime(bpf * 2 + this.eng.detune, t, tc)
    // Muffled from inside the flight deck, which is where the whine mostly goes.
    this.eng.whineG.gain.setTargetAtTime(n1 * v.whine * (inside ? 0.35 : 1), t, tc)
    this.eng.whine2G.gain.setTargetAtTime(n1 * n1 * v.whine2 * (inside ? 0.25 : 1), t, tc)
    // Reheat: a wide, low rip that opens as the nozzle does.
    if (v.burner) {
      this.eng.abG.gain.setTargetAtTime(ab * 0.62 * (inside ? 0.55 : 1), t, 0.05)
      this.eng.abBP.frequency.setTargetAtTime(180 + ab * 520, t, 0.06)
    } else if (this.eng.abG.gain.value > 0.0001) {
      this.eng.abG.gain.setTargetAtTime(0, t, 0.05)
    }
    const engVol = (0.12 + n1 * 0.55 + ab * 0.30) * (inside ? 0.6 * (1 - 0.72 * supers) : 1)
    this.eng.out.gain.setTargetAtTime(ac.crashed ? 0 : engVol, t, 0.15)

    // Airflow rises with indicated airspeed and with anything hanging out in it.
    const kt = ac.ias * 1.943844
    const drag = ac.gearPos * 0.35 + (ac.flapDeg / 40) * 0.3 + ac.spoilers * 0.3
    const airVol = clamp((kt - 40) / 320, 0, 1) * (0.22 + drag * 0.5) *
      (inside ? 0.7 * (1 - 0.45 * supers) : 1)
    this.air.out.gain.setTargetAtTime(airVol, t, tc)
    this.air.filter.frequency.setTargetAtTime(380 + kt * 5.5, t, tc)

    // Wheels. Only on the ground, and it grows with ground speed and braking.
    const gs = Math.hypot(ac.vel.x, ac.vel.z)
    const rollVol = ac.onGround ? clamp(gs / 70, 0, 1) * (0.28 + ac.brakes * 0.35) : 0
    this.roll.out.gain.setTargetAtTime(rollVol, t, 0.07)
    this.roll.filter.frequency.setTargetAtTime(90 + gs * 2.4, t, tc)

    /* --- Alerts -------------------------------------------------------------
       Three conditions, each with a recorded call on the types that have one
       and a synthesised tone on the types that do not. The pull-up call takes
       priority over the low-speed call, because terrain does. */
    const alive = !ac.crashed
    const stall = alive && ac.stalling
    const pull = alive && !ac.onGround && ac.radioAlt < 150 && ac.vel.y < -8 && ac.gearPos < 0.5
    const over = alive && ac.overspeed

    if (this.pack) {
      // Recorded: loop while the condition holds, stop the moment it clears.
      if (pull) this.loopClip(this.pack.pullup, 1.0)
      else this.stopClip(this.pack.pullup)
      if (stall && !pull) this.loopClip(this.pack.stall, 0.95)
      else this.stopClip(this.pack.stall)
      if (over) this.loopClip(this.pack.master, 0.8)
      else this.stopClip(this.pack.master)
      this.warn.out.gain.setTargetAtTime(0, t, 0.03)
      if (!alive) this.stopAllClips()
      // The height calls, on the types that have the voice for them.
      this.callouts(ac)
    } else {
      // Synthesised: an intermittent tone, not a siren.
      if (stall) {
        this.warnPhase += dt
        const on = (this.warnPhase % 0.44) < 0.22
        this.warn.out.gain.setTargetAtTime(on ? 0.5 : 0, t, 0.01)
      } else {
        this.warnPhase = 0
        this.warn.out.gain.setTargetAtTime(0, t, 0.03)
      }
      // Overspeed clacker, the one warning that really does clack.
      if (over) {
        this.clackPhase += dt
        if (this.clackPhase > 0.14) {
          this.clackPhase = 0
          this.blip(1500 + Math.random() * 200, 0.035, 'square', 0.10)
        }
      }
    }
  }

  suspend() { if (this.ctx && this.ctx.state === 'running') this.ctx.suspend() }
  resume() { if (this.ctx && this.enabled && this.ctx.state === 'suspended') this.ctx.resume() }
}
